    weights = [2, 3, 4, 5]
    values = [3, 4, 5, 6]
    capacity = 5
    max_value, chosen_items = knapsack_01(weights, values, capacity)
    print("Weights:", weights)
    print("Values: ", values)
    print("Capacity:", capacity)
    print("Maximum value obtainable:", max_value)
    print("Items chosen (indices):", chosen_items)
